import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';

// This runs in Node.js - Don't use client-side code here (browser APIs, JSX...)

/**
 * Creating a sidebar enables you to:
 - create an ordered group of docs
 - render a sidebar for each doc of that group
 - provide next/previous navigation

 The sidebars can be generated from the filesystem, or explicitly defined here.

 Create as many sidebars as you want.
 */
// One category per public entrypoint, in package.json#exports order.
const API_ENTRYPOINTS = [
  { dir: 'root', label: 'annotations-design-patterns' },
  { dir: 'decorators', label: '/decorators' },
  { dir: 'operators', label: '/operators' },
  { dir: 'pipe', label: '/pipe' },
  { dir: 'run', label: '/run' },
  { dir: 'policy', label: '/policy' },
  { dir: 'observability', label: '/observability' },
  { dir: 'store', label: '/store' },
  { dir: 'node', label: '/node' },
  { dir: 'experimental', label: '/experimental' },
];

// Entrypoints repeat category labels ("Classes"...) and re-export the same
// symbols (RetryOptions...); i18n needs a unique translation key for each item.
type GeneratedItem = { type: string; id?: string; label?: string; items?: GeneratedItem[] };
function withUniqueKeys(dir: string, items: GeneratedItem[]): GeneratedItem[] {
  return items.map((item) => ({
    ...item,
    key: `api-${dir}-${item.id ?? item.label}`,
    ...(item.items ? { items: withUniqueKeys(dir, item.items) } : {}),
  }));
}

const sidebars: SidebarsConfig = {
  tutorialSidebar: [
    'intro',
    {
      type: 'category',
      label: 'Guías',
      items: [
        'guides/decorators',
        'guides/operators',
        'guides/pipe',
        'guides/run',
        'guides/policy',
        'guides/observability',
        'guides/concurrency',
        'guides/store-node',
        'guides/experimental',
        'guides/granular-imports',
      ],
    },
    'migration/2.0',
  ],
  apiSidebar: API_ENTRYPOINTS.map(({ dir, label }) => ({
    type: 'category' as const,
    label,
    link: { type: 'doc' as const, id: `api/${dir}/index` },
    // Generated by docusaurus-plugin-typedoc before sidebars are loaded.
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    items: withUniqueKeys(dir, require(`./docs/api/${dir}/typedoc-sidebar.cjs`)),
  })) as SidebarsConfig[string],
};

export default sidebars;
