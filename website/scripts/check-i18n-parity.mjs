#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const websiteDir = path.join(__dirname, '..');
const docsDir = path.join(websiteDir, 'docs');
const enDocsDir = path.join(websiteDir, 'i18n', 'en', 'docusaurus-plugin-content-docs', 'current');

// Recursively get all markdown files in a directory, excluding api
function getMarkdownFiles(dir, baseDir = dir) {
  const files = [];
  const items = fs.readdirSync(dir);

  for (const item of items) {
    const fullPath = path.join(dir, item);
    const stat = fs.statSync(fullPath);

    // Skip api directory (autogenerated)
    if (item === 'api') continue;

    if (stat.isDirectory()) {
      files.push(...getMarkdownFiles(fullPath, baseDir));
    } else if (item.endsWith('.md') || item.endsWith('.mdx')) {
      const relativePath = path.relative(baseDir, fullPath);
      files.push(relativePath);
    }
  }

  return files;
}

// Get Spanish files
const esFiles = getMarkdownFiles(docsDir);
esFiles.sort();

// Get English files
const enFiles = new Set();
if (fs.existsSync(enDocsDir)) {
  getMarkdownFiles(enDocsDir).forEach((f) => enFiles.add(f));
}

// Check for missing English translations
const missing = [];
for (const esFile of esFiles) {
  if (!enFiles.has(esFile)) {
    missing.push(esFile);
  }
}

// Report
console.log(`\n📋 i18n Parity Check\n`);
console.log(`Spanish docs:  ${esFiles.length} files`);
console.log(`English docs:  ${enFiles.size} files`);

if (missing.length === 0) {
  console.log('\n✅ All Spanish docs have English translations.\n');
  process.exit(0);
} else {
  console.log(`\n❌ Missing English translations for ${missing.length} file(s):\n`);
  for (const file of missing) {
    console.log(`  - ${file}`);
  }
  console.log();
  process.exit(1);
}
